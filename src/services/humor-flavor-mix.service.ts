import { supabase } from "@/utils/supabase/client";
import {
  HumorFlavorMix,
  HumorFlavorMixInsert,
  HumorFlavorMixUpdate,
} from "@/types/humor-flavor-mix";
import { HumorFlavor } from "@/types/humor-flavor";
import {
  applyInsertAuditFields,
  applyUpdateAuditFields,
  getCurrentProfileId,
} from "@/utils/supabase/audit";

export interface HumorFlavorMixWithFlavor extends HumorFlavorMix {
  humor_flavor?: HumorFlavor;
}

export class HumorFlavorMixService {
  /**
   * Get all humor flavor mixes with optional flavor details
   */
  static async getAll(includeFlavor: boolean = true): Promise<HumorFlavorMixWithFlavor[]> {
    if (!supabase) return [];

    try {
      const query = supabase
        .from("humor_flavor_mix")
        .select(includeFlavor ? "*, humor_flavors(*)" : "*")
        .order("created_datetime_utc", { ascending: false });

      const { data, error } = await query;

      if (error) {
        console.error("Error fetching humor flavor mixes:", error);
        return [];
      }

      return (data || []).map((item: any) => {
        const mix: HumorFlavorMixWithFlavor = { ...item };
        
        if (includeFlavor && item.humor_flavors) {
          mix.humor_flavor = Array.isArray(item.humor_flavors) 
            ? item.humor_flavors[0] 
            : item.humor_flavors;
        }
        
        return mix;
      });
    } catch (error) {
      console.error("Error fetching humor flavor mixes:", error);
      return [];
    }
  }

  /**
   * Get a single humor flavor mix by ID
   */
  static async getById(id: number): Promise<HumorFlavorMixWithFlavor | null> {
    if (!supabase) return null;

    try {
      const { data, error } = await supabase
        .from("humor_flavor_mix")
        .select("*, humor_flavors(*)")
        .eq("id", id)
        .single();

      if (error) {
        console.error("Error fetching humor flavor mix:", error);
        return null;
      }

      const mix: HumorFlavorMixWithFlavor = { ...data };
      
      if (data.humor_flavors) {
        mix.humor_flavor = Array.isArray(data.humor_flavors) 
          ? data.humor_flavors[0] 
          : data.humor_flavors;
      }
      
      return mix;
    } catch (error) {
      console.error("Error fetching humor flavor mix:", error);
      return null;
    }
  }

  /**
   * Get humor flavor mixes by flavor ID
   */
  static async getByFlavorId(flavorId: number): Promise<HumorFlavorMix[]> {
    if (!supabase) return [];

    try {
      const { data, error } = await supabase
        .from("humor_flavor_mix")
        .select("*")
        .eq("humor_flavor_id", flavorId)
        .order("created_datetime_utc", { ascending: false });

      if (error) {
        console.error("Error fetching humor flavor mixes by flavor ID:", error);
        return [];
      }

      return (data || []) as HumorFlavorMix[];
    } catch (error) {
      console.error("Error fetching humor flavor mixes by flavor ID:", error);
      return [];
    }
  }

  /**
   * Create a new humor flavor mix
   * Note: The database auto-increments the id field using a sequence.
   * If you get a duplicate key error, the sequence may be out of sync.
   * Run this SQL to fix it:
   * SELECT setval('humor_flavor_mix_id_seq', (SELECT MAX(id) FROM humor_flavor_mix));
   */
  static async create(
    humorFlavorId: number,
    captionCount: number
  ): Promise<HumorFlavorMix | null> {
    if (!supabase) return null;

    try {
      // Explicitly only include the fields we want - no id, no created_datetime_utc (has default)
      // The id field is auto-generated by the database sequence
      const insertData: HumorFlavorMixInsert = {
        humor_flavor_id: humorFlavorId,
        caption_count: captionCount,
      };
      const profileId = await getCurrentProfileId(supabase);

      const { data, error } = await supabase
        .from("humor_flavor_mix")
        .insert(applyInsertAuditFields([insertData], profileId))
        .select()
        .single();

      if (error) {
        // Silently return null - error handling is done in the UI layer
        return null;
      }

      return data as HumorFlavorMix;
    } catch (error) {
      // Silently return null - error handling is done in the UI layer
      return null;
    }
  }

  /**
   * Update a humor flavor mix
   */
  static async update(
    id: number,
    updates: HumorFlavorMixUpdate
  ): Promise<HumorFlavorMix | null> {
    if (!supabase) return null;

    try {
      const profileId = await getCurrentProfileId(supabase);
      const { data, error } = await supabase
        .from("humor_flavor_mix")
        .update(applyUpdateAuditFields(updates, profileId))
        .eq("id", id)
        .select()
        .single();

      if (error) {
        console.error("Error updating humor flavor mix:", error);
        return null;
      }

      return data as HumorFlavorMix;
    } catch (error) {
      console.error("Error updating humor flavor mix:", error);
      return null;
    }
  }

  /**
   * Delete a humor flavor mix
   */
  static async delete(id: number): Promise<boolean> {
    if (!supabase) return false;

    try {
      const { error } = await supabase
        .from("humor_flavor_mix")
        .delete()
        .eq("id", id);

      if (error) {
        console.error("Error deleting humor flavor mix:", error);
        return false;
      }

      return true;
    } catch (error) {
      console.error("Error deleting humor flavor mix:", error);
      return false;
    }
  }

  /**
   * Get all humor flavor mixes filtered by theme ID
   */
  static async getByThemeId(themeId: number, includeFlavor: boolean = true): Promise<HumorFlavorMixWithFlavor[]> {
    if (!supabase) return [];

    try {
      // First get all flavor IDs for this theme
      const { data: mappings, error: mappingError } = await supabase
        .from("humor_flavor_theme_mappings")
        .select("humor_flavor_id")
        .eq("humor_theme_id", themeId);

      if (mappingError) {
        console.error("Error fetching flavor-theme mappings:", mappingError);
        return [];
      }

      if (!mappings || mappings.length === 0) {
        return [];
      }

      const flavorIds = mappings
        .map((m) => m.humor_flavor_id)
        .filter((id): id is number => typeof id === "number");

      if (flavorIds.length === 0) {
        return [];
      }

      // Then get all mixes for these flavors
      const query = supabase
        .from("humor_flavor_mix")
        .select(includeFlavor ? "*, humor_flavors(*)" : "*")
        .in("humor_flavor_id", flavorIds)
        .order("created_datetime_utc", { ascending: false });

      const { data, error } = await query;

      if (error) {
        console.error("Error fetching humor flavor mixes by theme:", error);
        return [];
      }

      return (data || []).map((item: any) => {
        const mix: HumorFlavorMixWithFlavor = { ...item };
        
        if (includeFlavor && item.humor_flavors) {
          mix.humor_flavor = Array.isArray(item.humor_flavors) 
            ? item.humor_flavors[0] 
            : item.humor_flavors;
        }
        
        return mix;
      });
    } catch (error) {
      console.error("Error fetching humor flavor mixes by theme:", error);
      return [];
    }
  }
}
