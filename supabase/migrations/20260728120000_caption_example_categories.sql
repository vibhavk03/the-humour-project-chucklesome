-- Normalizes caption example categories into a managed lookup table.
--
-- Mirrors public.common_use_categories: everyone can read the categories, only
-- superadmins manage the list. Replaces the earlier free-text
-- caption_examples.category column approach.

create table if not exists public.caption_example_categories (
  id bigint generated by default as identity primary key,
  name text not null,
  created_datetime_utc timestamptz not null default now(),
  modified_datetime_utc timestamptz not null default now(),
  created_by_user_id uuid default auth.uid(),
  modified_by_user_id uuid default auth.uid()
);

-- Category names are unique (case-insensitive).
create unique index if not exists caption_example_categories_name_key
  on public.caption_example_categories (lower(name));

alter table public.caption_example_categories enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'caption_example_categories'
      and policyname = 'All users can view caption example categories'
  ) then
    create policy "All users can view caption example categories"
      on public.caption_example_categories for select to authenticated using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'caption_example_categories'
      and policyname = 'Only superadmins can create caption example categories'
  ) then
    create policy "Only superadmins can create caption example categories"
      on public.caption_example_categories for insert to authenticated
      with check ((select public.is_superadmin(auth.uid())));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'caption_example_categories'
      and policyname = 'Only superadmins can update caption example categories'
  ) then
    create policy "Only superadmins can update caption example categories"
      on public.caption_example_categories for update to authenticated
      using ((select public.is_superadmin(auth.uid())))
      with check ((select public.is_superadmin(auth.uid())));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'caption_example_categories'
      and policyname = 'Only superadmins can delete caption example categories'
  ) then
    create policy "Only superadmins can delete caption example categories"
      on public.caption_example_categories for delete to authenticated
      using ((select public.is_superadmin(auth.uid())));
  end if;
end $$;

-- Link caption_examples to a category (nullable so existing rows are unaffected).
alter table public.caption_examples
  add column if not exists caption_example_category_id bigint
    references public.caption_example_categories (id) on delete set null;

create index if not exists caption_examples_category_id_idx
  on public.caption_examples (caption_example_category_id);

-- Starter categories (superadmins can rename / add / remove later).
insert into public.caption_example_categories (name)
values ('General'), ('Campus Life'), ('Academics'), ('Social'), ('Food'), ('Sports')
on conflict do nothing;
